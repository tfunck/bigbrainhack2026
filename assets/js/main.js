const CFG = window.SITE || {};
const REPO = CFG.repo || "";
const LABEL = CFG.projectLabel || "Project";

/* -------------------------------------------------------------------------
   1. Hero: reassemble a coronal section out of horizontal scanlines.
   ---------------------------------------------------------------------- */
(function drawSection() {
  const g = document.getElementById("scanlines");
  if (!g) return;

  const TOP = 44, BOTTOM = 468, STEP = 6, LEFT = 120, RIGHT = 680;
  const NS = "http://www.w3.org/2000/svg";
  const rows = Math.floor((BOTTOM - TOP) / STEP);

  for (let i = 0; i <= rows; i++) {
    const y = TOP + i * STEP;
    const t = i / rows;
    // Laminar texture: opacity waves down the section, denser mid-cortex.
    const wave = 0.45 + 0.42 * Math.abs(Math.sin(t * Math.PI * 3.1 + 0.4));
    const line = document.createElementNS(NS, "line");
    line.setAttribute("x1", LEFT);
    line.setAttribute("x2", RIGHT);
    line.setAttribute("y1", y);
    line.setAttribute("y2", y);
    line.setAttribute("stroke-width", (1.1 + wave * 1.9).toFixed(2));
    line.style.setProperty("--o", wave.toFixed(2));
    line.style.setProperty("--d", (i * 0.022).toFixed(3) + "s");
    line.style.setProperty("--dx", (i % 2 ? -16 : 16) + "px");
    g.appendChild(line);
  }
})();

/* -------------------------------------------------------------------------
   2. Wire up the configurable links.
   ---------------------------------------------------------------------- */
(function wireLinks() {
  const issueNew = REPO
    ? `https://github.com/${REPO}/issues/new?template=project-pitch.yml&labels=${encodeURIComponent(LABEL)}`
    : null;
  const issueList = REPO
    ? `https://github.com/${REPO}/issues?q=is%3Aissue+is%3Aopen+label%3A%22${encodeURIComponent(LABEL)}%22`
    : null;

  set("[data-submit-project]", issueNew);
  set("[data-browse-issues]", issueList);
  set("[data-repo-link]", REPO ? `https://github.com/${REPO}` : null);

  const reg = CFG.registrationUrl;
  const live = reg && reg !== "#";
  document.querySelectorAll("[data-register]").forEach((el) => {
    if (live) {
      el.href = reg;
      if (el.tagName === "A" && el.hostname !== location.hostname) el.rel = "noopener";
    } else if (el.closest(".register")) {
      el.setAttribute("aria-disabled", "true");
      el.href = "#register";
    }
  });
  const note = document.querySelector("[data-register-note]");
  if (note && !live) note.hidden = false;

  function set(sel, href) {
    document.querySelectorAll(sel).forEach((el) => {
      if (href) {
        el.href = href;
        el.rel = "noopener";
      } else {
        el.setAttribute("aria-disabled", "true");
      }
    });
  }
})();

/* -------------------------------------------------------------------------
   3. Projects.
   Primary source: projects.json, regenerated by the GitHub Action on every
   issue event. Fallback: the public GitHub API, so the page is never stale
   even between Action runs.
   ---------------------------------------------------------------------- */
const grid = document.getElementById("projects-grid");
const countEl = document.getElementById("projects-count");
const emptyEl = document.getElementById("projects-empty");
const filtersEl = document.getElementById("projects-filters");

let PROJECTS = [];
let activeTheme = "All";

init();

async function init() {
  if (!grid) return;
  try {
    PROJECTS = await loadFromFile();
    if (!PROJECTS.length) PROJECTS = await loadFromApi();
  } catch (err) {
    try {
      PROJECTS = await loadFromApi();
    } catch (err2) {
      console.warn("Could not load projects:", err2);
      PROJECTS = [];
    }
  }
  renderFilters();
  render();
}

async function loadFromFile() {
  const res = await fetch("projects.json", { cache: "no-cache" });
  if (!res.ok) throw new Error("projects.json not available");
  const data = await res.json();
  return Array.isArray(data.projects) ? data.projects : [];
}

async function loadFromApi() {
  if (!REPO || REPO.startsWith("OWNER/")) return [];
  const url = `https://api.github.com/repos/${REPO}/issues?state=open&per_page=100&labels=${encodeURIComponent(LABEL)}`;
  const res = await fetch(url);
  if (!res.ok) throw new Error("GitHub API " + res.status);
  const issues = await res.json();
  return issues.filter((i) => !i.pull_request).map(parseIssue);
}

/* Parse a GitHub issue-form body: "### Label\n\nvalue\n\n### Label\n\nvalue" */
function parseIssue(issue) {
  const fields = {};
  (issue.body || "").split(/^###\s+/m).forEach((block) => {
    const nl = block.indexOf("\n");
    if (nl === -1) return;
    const key = block.slice(0, nl).trim().toLowerCase();
    let val = block.slice(nl).trim();
    if (!val || val === "_No response_") val = "";
    fields[key] = val;
  });

  const pick = (...keys) => {
    for (const k of keys) {
      const hit = Object.keys(fields).find((f) => f.startsWith(k));
      if (hit && fields[hit]) return fields[hit];
    }
    return "";
  };

  const themes = pick("theme")
    .split(/[\n,]/)
    .map((s) => s.replace(/^[-*]\s*/, "").replace(/^\[[xX ]\]\s*/, "").trim())
    .filter(Boolean);

  const gpu = /yes/i.test(pick("gb10", "would this project"));

  return {
    number: issue.number,
    title: pick("project title") || issue.title,
    description: pick("short description", "description"),
    url: issue.html_url,
    projectUrl: firstUrl(pick("project link", "link to")),
    image: firstUrl(pick("image", "logo")),
    leads: pick("project lead").split("\n").map((s) => s.trim()).filter(Boolean),
    themes,
    gpu
  };
}

function firstUrl(text) {
  const m = (text || "").match(/https?:\/\/[^\s)"'<>]+/);
  return m ? m[0] : "";
}

function renderFilters() {
  if (!filtersEl) return;
  const themes = ["All", ...new Set(PROJECTS.flatMap((p) => p.themes))].filter(Boolean);
  if (themes.length < 3) { filtersEl.innerHTML = ""; return; }
  filtersEl.innerHTML = "";
  themes.forEach((theme) => {
    const b = document.createElement("button");
    b.className = "chip";
    b.type = "button";
    b.textContent = theme;
    b.setAttribute("aria-pressed", String(theme === activeTheme));
    b.addEventListener("click", () => {
      activeTheme = theme;
      filtersEl.querySelectorAll(".chip").forEach((c) =>
        c.setAttribute("aria-pressed", String(c.textContent === theme))
      );
      render();
    });
    filtersEl.appendChild(b);
  });
}

function render() {
  const shown = PROJECTS.filter(
    (p) => activeTheme === "All" || p.themes.includes(activeTheme)
  );

  grid.innerHTML = "";
  emptyEl.hidden = PROJECTS.length > 0;

  countEl.textContent = PROJECTS.length
    ? `${shown.length} of ${PROJECTS.length} project${PROJECTS.length === 1 ? "" : "s"}`
    : "";

  shown.forEach((p) => grid.appendChild(card(p)));
}

function card(p) {
  const a = document.createElement("a");
  a.className = "card";
  a.href = p.url;
  a.rel = "noopener";

  if (p.image) {
    const img = document.createElement("img");
    img.className = "card__thumb";
    img.src = p.image;
    img.alt = "";
    img.loading = "lazy";
    img.addEventListener("error", () => img.remove());
    a.appendChild(img);
  }

  a.insertAdjacentHTML(
    "beforeend",
    `<p class="card__num">#${p.number}</p>
     <h3 class="card__title">${esc(p.title)}</h3>
     <p class="card__desc">${esc(p.description)}</p>`
  );

  const meta = document.createElement("div");
  meta.className = "card__meta";
  p.themes.slice(0, 2).forEach((t) => {
    const tag = document.createElement("span");
    tag.className = "tag";
    tag.textContent = t;
    meta.appendChild(tag);
  });
  if (p.gpu) {
    const tag = document.createElement("span");
    tag.className = "tag tag--gpu";
    tag.textContent = "GB10";
    meta.appendChild(tag);
  }
  if (p.leads.length) {
    const lead = document.createElement("span");
    lead.className = "card__lead";
    lead.textContent = p.leads[0].split(",")[0];
    meta.appendChild(lead);
  }
  a.appendChild(meta);
  return a;
}

function esc(s) {
  const d = document.createElement("div");
  d.textContent = s || "";
  return d.innerHTML;
}
